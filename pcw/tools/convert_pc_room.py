#!/usr/bin/env python3
"""Convert the original PC Rick Dangerous start room and PC tile bank for PCW."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


def strip_comments(source: str) -> str:
    source = re.sub(r"/\*[\s\S]*?\*/", "", source)
    return re.sub(r"//[^\n]*", "", source)


def extract_initializer(source: str, name: str) -> str:
    pattern = re.compile(
        rf"\b{re.escape(name)}\s*(?:\[[^\]]*\]\s*)*=\s*\{{"
    )
    match = pattern.search(source)
    if not match:
        raise ValueError(f"could not find initializer for {name}")

    start = source.find("{", match.start())
    depth = 0
    for pos in range(start, len(source)):
        char = source[pos]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return source[start + 1:pos]
    raise ValueError(f"unterminated initializer for {name}")


def parse_c_integer(token: str) -> int:
    token = token.strip()
    if token.lower().startswith("0x"):
        return int(token, 16)
    if len(token) > 1 and token.startswith("0"):
        return int(token, 8)
    return int(token, 10)


def parse_values(initializer: str) -> list[int]:
    tokens = re.findall(r"0[xX][0-9a-fA-F]+|0[0-7]+|[0-9]+", initializer)
    return [parse_c_integer(token) for token in tokens]


def fmt_byte(value: int) -> str:
    digits = f"{value:02X}"
    if digits[0] in "ABCDEF":
        digits = "0" + digits
    return f"{digits}h"


def convert_tile_word(word: int) -> int:
    """Retain the low bit of each of the word's eight 2-bit CGA pixels."""
    result = 0
    for x in range(8):
        source_bit = 14 - 2 * x
        destination_bit = 7 - x
        result |= ((word >> source_bit) & 1) << destination_bit
    return result


def build_first_room(map_source: str, tile_source: str) -> tuple[list[list[int]], list[int], int]:
    maps = strip_comments(map_source)
    tiles = strip_comments(tile_source)

    blocks = parse_values(extract_initializer(maps, "map_blocks"))
    block_numbers = parse_values(extract_initializer(maps, "map_bnums"))
    submaps = parse_values(extract_initializer(maps, "map_submaps"))
    map_starts = parse_values(extract_initializer(maps, "map_maps"))
    tile_words = parse_values(extract_initializer(tiles, "tiles_banks"))

    if len(blocks) != 256 * 16:
        raise ValueError(f"map_blocks contains {len(blocks)} values; expected 4096")
    if len(submaps) < 4 or len(map_starts) < 5:
        raise ValueError("map metadata is incomplete")
    if len(tile_words) != 4 * 256 * 8:
        raise ValueError(
            f"tiles_banks contains {len(tile_words)} words; expected 8192"
        )

    # map_maps[0] is {x, y, starting tile row, submap, tune}.
    first = map_starts[:5]
    map_row = first[2]
    submap_number = first[3]
    submap_base = submap_number * 4
    if submap_base + 3 >= len(submaps):
        raise ValueError("first map refers to a missing submap")
    page = submaps[submap_base]
    block_base = submaps[submap_base + 1]
    tile_bank = 3 if page == 1 else 2

    # Match map_expand() in xrick/src/rd1/maps.c.
    block_number_index = block_base + ((2 * map_row) & 0xFFF8)
    grid = [[0] * 32 for _ in range(44)]

    for block_row in range(11):
        for block_col in range(8):
            if block_number_index >= len(block_numbers):
                raise ValueError("map block-number table is too short")
            block_number = block_numbers[block_number_index]
            block_number_index += 1
            if not 0 <= block_number < 256:
                raise ValueError(f"invalid block number {block_number}")
            block = blocks[block_number * 16:(block_number + 1) * 16]
            for row in range(4):
                for col in range(4):
                    grid[block_row * 4 + row][block_col * 4 + col] = (
                        block[row * 4 + col]
                    )

    visible = grid[8:32]
    if len(visible) != 24 or any(len(row) != 32 for row in visible):
        raise ValueError("expanded room does not have the expected 32x24 tiles")
    if any(tile < 0 or tile > 255 for row in visible for tile in row):
        raise ValueError("room contains a tile number outside 0..255")

    start = tile_bank * 256 * 8
    bank_words = tile_words[start:start + 256 * 8]
    if len(bank_words) != 256 * 8:
        raise ValueError(f"PC tile bank {tile_bank} is incomplete")
    bank_bytes = [convert_tile_word(word) for word in bank_words]
    return visible, bank_bytes, tile_bank


def generate_include(room: list[list[int]], tile_bytes: list[int], bank: int) -> str:
    lines = [
        "; Generated by tools/convert_pc_room.py -- do not edit.",
        "; First PC map entry, expanded from 4x4 blocks to 32x24 tiles.",
        "; Tile data is the original PC CGA bank projected to monochrome.",
        "; Pixel mapping retains the low bit of each 2-bit CGA palette index.",
        "",
        "PCW_MAP0:",
    ]

    for row_number, row in enumerate(room):
        lines.append(f"; room tile row {row_number:02d}")
        for half in range(2):
            values = row[half * 16:(half + 1) * 16]
            lines.append("        DB      " + ",".join(fmt_byte(v) for v in values))

    lines.extend(["", f"PCW_TILE_BANK{bank}:"])
    for tile in range(256):
        lines.append(f"; tile {tile:03d}")
        for row in range(8):
            base = tile * 8 + row
            values = tile_bytes[base:base + 8]
            lines.append("        DB      " + ",".join(fmt_byte(v) for v in values))

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("maps", type=Path, help="path to xrick/src/rd1/dat_maps.c")
    parser.add_argument("tiles", type=Path, help="path to xrick/src/rd1/dat_tilesPC.c")
    parser.add_argument("output", type=Path, help="output Z80 assembler include")
    args = parser.parse_args()

    try:
        map_source = args.maps.read_text(encoding="utf-8")
        tile_source = args.tiles.read_text(encoding="utf-8")
        room, tile_bytes, bank = build_first_room(map_source, tile_source)
        if bank != 2:
            raise ValueError(
                f"first room uses tile bank {bank}, but PCWROOM expects bank 2"
            )
        output = generate_include(room, tile_bytes, bank)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output, encoding="ascii", newline="\n")
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    used = sorted({tile for row in room for tile in row})
    print(
        f"Converted map 0: 32x24 tiles, tile bank {bank}, "
        f"{len(used)} unique tiles -> {args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
