#!/usr/bin/env python3
"""Convert Xrick's original PC/CGA sprite table to the PCW monochrome format.

Input records in dat_spritesPC.c are stored sprite -> column -> row.
Output records are stored sprite -> row -> column, with each source byte
represented by an interleaved MASK,PIXELS pair.

The source uses two bits per pixel. We retain the low bit of each CGA
colour index: with Xrick's PC palette this maps indices 0/2 to black and
1/3 to white. This is also an exact projection of the original drawing
operation ((old & mask) | pict) onto that retained bit.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SPRITE_COUNT = 0x9B
COLUMNS = 4
HEIGHT = 0x15
PIXELS_PER_WORD = 8
PAIR_RE = re.compile(
    r"\{\s*(0[xX][0-9a-fA-F]+|[0-9]+)\s*,\s*"
    r"(0[xX][0-9a-fA-F]+|[0-9]+)\s*\}"
)


def parse_c_integer(token: str) -> int:
    token = token.strip()
    if token.lower().startswith("0x"):
        return int(token, 16)
    if len(token) > 1 and token.startswith("0"):
        return int(token, 8)
    return int(token, 10)


def convert_word(mask_word: int, picture_word: int) -> tuple[int, int]:
    """Project eight 2-bit CGA pixels to one monochrome mask/pixel pair."""
    mask_byte = 0
    picture_byte = 0
    for x in range(PIXELS_PER_WORD):
        shift = 14 - 2 * x
        out_bit = 7 - x
        mask_byte |= ((mask_word >> shift) & 1) << out_bit
        picture_byte |= ((picture_word >> shift) & 1) << out_bit
    return mask_byte, picture_byte


def fmt_byte(value: int) -> str:
    # z80asm requires a leading decimal digit for hexadecimal literals;
    # values beginning A-F must therefore be written as 0ABh, not ABh.
    digits = f"{value:02X}"
    if digits[0] in "ABCDEF":
        digits = "0" + digits
    return f"{digits}h"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="path to dat_spritesPC.c")
    parser.add_argument("output", type=Path, help="output Z80 assembler include")
    args = parser.parse_args()

    try:
        text = args.source.read_text(encoding="utf-8")
    except OSError as exc:
        print(f"error: cannot read {args.source}: {exc}", file=sys.stderr)
        return 2

    raw_pairs = PAIR_RE.findall(text)
    expected = SPRITE_COUNT * COLUMNS * HEIGHT
    if len(raw_pairs) != expected:
        print(
            f"error: found {len(raw_pairs)} sprite words; expected {expected} "
            f"({SPRITE_COUNT} sprites x {COLUMNS} columns x {HEIGHT} rows)",
            file=sys.stderr,
        )
        return 2

    words = [(parse_c_integer(mask), parse_c_integer(pic))
             for mask, pic in raw_pairs]

    lines = [
        "; Generated by tools/convert_pc_sprites.py -- do not edit.",
        "; Original PC sprite order: sprite, column, scanline.",
        "; Converted order: sprite, scanline, 8-pixel column.",
        "; Each pair is MASK,PIXELS; mask bit 1 preserves destination.",
        "; CGA colour-index low bit retained: 0/2 -> black, 1/3 -> white.",
        "",
    ]

    for sprite in range(SPRITE_COUNT):
        lines.append(f"PCW_SPRITE_{sprite:03d}:")
        base = sprite * COLUMNS * HEIGHT
        for row in range(HEIGHT):
            values: list[str] = []
            for column in range(COLUMNS):
                mask_word, picture_word = words[base + column * HEIGHT + row]
                mask_byte, picture_byte = convert_word(mask_word, picture_word)
                values.extend((fmt_byte(mask_byte), fmt_byte(picture_byte)))
            lines.append("        DB      " + ",".join(values))

    output = "\n".join(lines) + "\n"
    try:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output, encoding="ascii", newline="\n")
    except OSError as exc:
        print(f"error: cannot write {args.output}: {exc}", file=sys.stderr)
        return 2

    byte_count = SPRITE_COUNT * HEIGHT * COLUMNS * 2
    print(
        f"Converted {SPRITE_COUNT} sprites: {byte_count} data bytes "
        f"({COLUMNS * 8}x{HEIGHT} pixels each) to {args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
