#!/usr/bin/env python3
"""Convert selected original PC Rick frames to the full-screen PCW scale."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SPRITE_COUNT = 0x9B
SPRITE_WIDTH = 32
SPRITE_HEIGHT = 0x15
SCREEN_WIDTH = 720
SCREEN_HEIGHT = 256
ROOM_WIDTH = 256
ROOM_HEIGHT = 192
OUTPUT_WIDTH = 96
OUTPUT_HEIGHT = 28

# Right/left walk cycles, idle poses and jump poses used by e_rick.c.
FRAME_IDS = (0x01, 0x02, 0x03, 0x04, 0x05,
             0x06, 0x0B,
             0x0D, 0x0E, 0x0F, 0x10, 0x11,
             0x15, 0x17)


def strip_comments(source: str) -> str:
    source = re.sub(r"/\*[\s\S]*?\*/", "", source)
    return re.sub(r"//[^\n]*", "", source)


def parse_c_integer(token: str) -> int:
    token = token.strip()
    if token.lower().startswith("0x"):
        return int(token, 16)
    if len(token) > 1 and token.startswith("0"):
        return int(token, 8)
    return int(token, 10)


def fmt_byte(value: int) -> str:
    digits = f"{value:02X}"
    if digits[0] in "ABCDEF":
        digits = "0" + digits
    return f"{digits}h"


def load_pairs(source: str) -> list[tuple[int, int]]:
    source = strip_comments(source)
    pair_re = re.compile(
        r"\{\s*(0[xX][0-9a-fA-F]+|0[0-7]+|[0-9]+)\s*,\s*"
        r"(0[xX][0-9a-fA-F]+|0[0-7]+|[0-9]+)\s*\}"
    )
    pairs = [
        (parse_c_integer(mask), parse_c_integer(picture))
        for mask, picture in pair_re.findall(source)
    ]
    expected = SPRITE_COUNT * 4 * SPRITE_HEIGHT
    if len(pairs) != expected:
        raise ValueError(
            f"sprite source has {len(pairs)} mask/picture pairs; expected {expected}"
        )
    if any(mask > 0xFFFF or picture > 0xFFFF for mask, picture in pairs):
        raise ValueError("sprite source contains a value wider than 16 bits")
    return pairs


def scaled_frame(
    pairs: list[tuple[int, int]], sprite_id: int
) -> list[list[tuple[int, int]]]:
    """Return 96 mask/pixel bits per row; last six pixels are transparent."""
    base = sprite_id * 4 * SPRITE_HEIGHT
    rows: list[list[tuple[int, int]]] = []
    for out_y in range(OUTPUT_HEIGHT):
        src_y = (out_y * ROOM_HEIGHT) // SCREEN_HEIGHT
        bits: list[tuple[int, int]] = []
        for out_x in range(OUTPUT_WIDTH):
            if out_x >= 90:
                bits.append((1, 0))
                continue
            src_x = (out_x * ROOM_WIDTH) // SCREEN_WIDTH
            column, local_x = divmod(src_x, 8)
            mask_word, picture_word = pairs[
                base + column * SPRITE_HEIGHT + src_y
            ]
            shift = 14 - 2 * local_x
            bits.append(((mask_word >> shift) & 1,
                         (picture_word >> shift) & 1))
        rows.append(bits)
    return rows


def pack_row(bits: list[tuple[int, int]]) -> tuple[list[int], list[int]]:
    masks = [0] * (OUTPUT_WIDTH // 8)
    pixels = [0] * (OUTPUT_WIDTH // 8)
    for x, (mask, pixel) in enumerate(bits):
        bit = 1 << (7 - (x & 7))
        if mask:
            masks[x >> 3] |= bit
        if pixel:
            pixels[x >> 3] |= bit
    return masks, pixels


def generate_include(pairs: list[tuple[int, int]]) -> str:
    lines = [
        "; Generated by tools/convert_pc_player.py -- do not edit.",
        "; Original PC frames scaled exactly like the 256x192 room image.",
        "; Each frame is 96x28, MASK then PIXELS, MSB first per row.",
        "; The final six columns are transparent padding (screen sprite is 90px wide).",
        "",
    ]
    for sprite_id in FRAME_IDS:
        # Keep frame 0x10 comfortably inside the upper TPA window rather
        # than starting at its 8000h boundary. Use the assembler's current
        # address so additions to the code/background do not break alignment.
        # build.sh verifies that this resolves to 8400h.
        if sprite_id == 0x10:
            lines.append("; Place frame 10 safely inside the upper TPA bank.")
            lines.append("        DS      08400h-$")
        lines.append(f"PCW_PLAYER_{sprite_id:02X}:")
        rows = scaled_frame(pairs, sprite_id)
        for row in rows:
            masks, pixels = pack_row(row)
            values = [value for pair in zip(masks, pixels) for value in pair]
            # Keep assembler lines short while preserving interleaved pairs.
            for start in range(0, len(values), 12):
                chunk = values[start:start + 12]
                lines.append("        DB      " + ",".join(fmt_byte(v) for v in chunk))
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="path to dat_spritesPC.c")
    parser.add_argument("output", type=Path, help="output Z80 assembler include")
    args = parser.parse_args()

    try:
        pairs = load_pairs(args.source.read_text(encoding="utf-8"))
        output = generate_include(pairs)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output, encoding="ascii", newline="\n")
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    print(
        f"Converted {len(FRAME_IDS)} Rick frames to "
        f"{OUTPUT_WIDTH}x{OUTPUT_HEIGHT} PCW-scale masked sprites: {args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
